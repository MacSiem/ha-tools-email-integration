class Node:
    def __init__(self,tag,parent=None,text=''):
        self.tag,self.parent,self.text=tag,parent,text
    def inside(self,ancestor):
        current=self
        while current:
            if current is ancestor:return True
            current=current.parent
        return False

class Document(HTMLParser):
    def __init__(self,html):
        super().__init__(convert_charrefs=True);self.root=Node('document');self.stack=[self.root];self.nodes=[];self.feed(html)
    def handle_starttag(self,tag,attrs):
        node=Node(tag,self.stack[-1]);self.nodes.append(node)
        if tag not in {'br','hr','meta','link','img','input','wbr'}:self.stack.append(node)
    def handle_endtag(self,tag):
        for i in range(len(self.stack)-1,0,-1):
            if self.stack[i].tag==tag:
                del self.stack[i:];break
    def handle_data(self,data):
        if data.strip():self.nodes.append(Node('#text',self.stack[-1],data.strip()))

class MailLayoutTest(unittest.IsolatedAsyncioTestCase):
    def assert_coherent(self,payload):
        doc=Document(payload['html']);body=next(n for n in doc.nodes if n.tag=='body')
        title=next(n for n in doc.nodes if n.tag=='h1');column=title.parent
        while column.parent is not body:column=column.parent
        text=[n for n in doc.nodes if n.tag=='#text' and n.inside(body)]
        self.assertTrue(all(n.inside(column) for n in text),'Every visible section, including source context and charts, belongs to the title column')
        self.assertEqual('Generated by HA Tools Email',text[-1].text,'The footer ends the complete report, after charts and comparisons')
        self.assertEqual(1,sum(n.text=='Generated by HA Tools Email' for n in text))
        self.assertFalse(any(n.tag in {'script','img','iframe'} for n in doc.nodes))

    async def test_energy_builder_keeps_its_charts_before_footer_in_same_column(self):
        p=c.build_energy_report_payload([{'name':'Meter <safe>', 'kwh':2}],cadence='daily',currency='EUR')
        self.assert_coherent(p)
        self.assertIn('Meter &lt;safe&gt;',p['html'])

    async def test_log_builder_keeps_its_charts_before_footer_in_same_column(self):
        p=c.build_log_digest_payload([{'name':'Fixture <safe>','message':'Warning','level':'WARNING','count':2}],cadence='monthly')
        self.assert_coherent(p)

    async def test_calendar_runtime_keeps_context_comparison_and_charts_together(self):
        start=datetime(2026,3,30,tzinfo=timezone.utc);end=datetime(2026,3,31,tzinfo=timezone.utc)
        async def executor(fn,*args):return fn(*args)
        async def prefs(hass):return types.SimpleNamespace(data={'energy_sources':[{'type':'grid','stat_energy_from':'sensor.grid'}]})
        energy=types.ModuleType('homeassistant.components.energy.data');energy.async_get_manager=prefs
        hass=types.SimpleNamespace(data={},states={},async_add_executor_job=executor,config=types.SimpleNamespace(currency='EUR',time_zone='UTC'))
        async def usage(hass,sensors,begin,finish,cadence):return snapshot(24 if begin==start else 12)
        with patch.dict('sys.modules',{energy.__name__:energy}),patch.object(c,'async_get_energy_usage',side_effect=usage):
            p=await c.async_build_energy_report_payload(hass,cadence='daily',now=end,window_start=start,window_end=end,report_timezone='UTC')
        self.assert_coherent(p)
        self.assertIn('Previous period comparison',p['html'])
        self.assertIn('Grid import from Energy Dashboard',p['html'])

    async def test_log_runtime_retention_context_stays_in_complete_column(self):
        class Store:
            async def async_get_digest_state(self,*args):return {}
        hass=types.SimpleNamespace(data={'system_log':types.SimpleNamespace(records=[])})
        p=await c.async_build_log_digest_payload(hass,Store(),cadence='weekly',now=datetime(2026,3,31,tzinfo=timezone.utc))
        self.assert_coherent(p)
        self.assertIn('Counts describe retained aggregates',p['html'])
