    async def test_dark_contract_and_explicit_light_seam_are_shared(self):
        for payload in (c.build_energy_report_payload([],cadence='daily'),
                        c.build_log_digest_payload([],cadence='daily')):
            self.assert_coherent(payload)
            html=payload['html']
            for token in ('name="color-scheme" content="light dark"',
                          'name="supported-color-schemes" content="light dark"',
                          'name="ha-tools-mail-presentation" content="1"',
                          '@media (prefers-color-scheme:dark)', '[data-ogsc]',
                          'html[data-mail-preview-theme="light"]',
                          'html[data-mail-preview-theme="dark"]',
                          'html:not([data-mail-preview-theme="light"])',
                          'class="mail-page"', 'class="mail-surface"', 'class="mail-card"'):
                self.assertIn(token,html)
            self.assertLess(html.index('@media'),html.index('html[data-mail-preview-theme="light"]'))
