    async def test_dark_contract_and_explicit_light_seam_are_shared(self):
        for payload in (c.build_energy_report_payload([],cadence='daily'),
                        c.build_log_digest_payload([],cadence='daily')):
            self.assert_coherent(payload)
            html=payload['html']
            for token in ('name="color-scheme" content="light dark"',
                          'name="supported-color-schemes" content="light dark"',
                          'name="ha-tools-mail-presentation" content="1"',
                          '@media (prefers-color-scheme:dark)', '[data-ogsc]',
                          'html[data-mail-preview-theme="light"]',
                          'html[data-mail-preview-theme="dark"]',
                          'html:not([data-mail-preview-theme="light"])',
                          'class="mail-page"', 'class="mail-surface"', 'class="mail-card"'):
                self.assertIn(token,html)
            self.assertLess(html.index('@media'),html.index('html[data-mail-preview-theme="light"]'))
            for token in ('filter:', 'url(', '@import', '<script', '<img'):
                self.assertNotIn(token,html)

    async def test_polish_runtime_uses_ha_presentation_not_report_calendar(self):
        now=datetime(2026,10,17,23,3,tzinfo=timezone.utc)
        start=datetime(2026,10,16,22,tzinfo=timezone.utc)
        end=datetime(2026,10,17,22,tzinfo=timezone.utc)
        hass=types.SimpleNamespace(config=types.SimpleNamespace(language='pl-PL',time_zone='Europe/Warsaw',currency='PLN'),
                                   data={'system_log':types.SimpleNamespace(records=[])})
        async def usage(*args):return snapshot(24)
        class Store:
            async def async_get_digest_state(self,*args):return {}
        with patch.object(c,'async_get_energy_usage',side_effect=usage):
            for kind in ('log_digest','energy_report'):
                payload=await c.async_build_report_payload(hass,Store(),kind=kind,cadence='daily',now=now,
                    window_start=start,window_end=end,report_timezone='America/New_York',
                    period_semantics='previous_completed_calendar_period')
                self.assert_coherent(payload,'Wygenerowano przez HA Tools Email')
                for field in ('subject','body','html'):
                    self.assertIn('18 paź 2026, 01:03 CEST (+0200)',payload[field])
                self.assertIn('Data raportu',payload['html'])
                self.assertIn('Okres raportu',payload['body'])
                self.assertEqual(start.isoformat(),payload['summary']['period']['from'])
                self.assertEqual(end.isoformat(),payload['summary']['period']['to'])
                self.assertIn('Czas techniczny UTC',payload['body'])
                self.assertTrue(payload['body'].endswith('Wygenerowano przez HA Tools Email'))
                if kind=='energy_report':
                    self.assertEqual('America/New_York',payload['summary']['visualization']['timezone'])
                else:
                    self.assertTrue(payload['subject'].startswith('HA Log Digest – dzienny'))

