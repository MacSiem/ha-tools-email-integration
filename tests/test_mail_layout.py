class Node:
    def __init__(self,tag,parent=None,text=''):
        self.tag,self.parent,self.text=tag,parent,text
    def inside(self,ancestor):
        current=self
        while current:
            if current is ancestor:return True
            current=current.parent
        return False

class Document(HTMLParser):
    def __init__(self,html):
        super().__init__(convert_charrefs=True);self.root=Node('document');self.stack=[self.root];self.nodes=[];self.feed(html)
    def handle_starttag(self,tag,attrs):
        node=Node(tag,self.stack[-1]);self.nodes.append(node)
        if tag not in {'br','hr','meta','link','img','input','wbr'}:self.stack.append(node)
    def handle_endtag(self,tag):
        for i in range(len(self.stack)-1,0,-1):
            if self.stack[i].tag==tag:
                del self.stack[i:];break
    def handle_data(self,data):
        if data.strip():self.nodes.append(Node('#text',self.stack[-1],data.strip()))

class MailLayoutTest(unittest.IsolatedAsyncioTestCase):
    def assert_coherent(self,payload,footer="Generated by HA Tools Email"):
        doc=Document(payload['html']);body=next(n for n in doc.nodes if n.tag=='body')
        title=next(n for n in doc.nodes if n.tag=='h1');column=title.parent
        while column.parent is not body:column=column.parent
        text=[n for n in doc.nodes if n.tag=='#text' and n.inside(body)]
        self.assertTrue(all(n.inside(column) for n in text),'Every visible section, including source context and charts, belongs to the title column')
        self.assertEqual(footer,text[-1].text,'The footer ends the complete report, after charts and comparisons')
        self.assertEqual(1,sum(n.text==footer for n in text))
        self.assertFalse(any(n.tag in {'script','img','iframe'} for n in doc.nodes))

    def assert_schema2_coherent(self,payload,*,polish=False):
        doc=Document(payload['html']);body=next(n for n in doc.nodes if n.tag=='body')
        column=next(n for n in doc.nodes if n.tag=='table' and n.parent is body)
        text=[n for n in doc.nodes if n.tag=='#text' and n.inside(body)]
        self.assertTrue(all(n.inside(column) for n in text))
        ending=('Alternatywy: te same pomiary; raport nie aktywuje taryfy.' if polish else
                'Alternatives use the same measurements; this report does not activate a tariff.')
        self.assertEqual(ending,text[-1].text)
        self.assertEqual(1,sum(n.text==ending for n in text))
        self.assertEqual(1,sum(n.text==payload['snapshot_id'] for n in text))
        self.assertFalse(any(n.tag in {'script','img','iframe'} for n in doc.nodes))

